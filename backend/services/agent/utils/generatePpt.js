import PptxGenJS from "pptxgenjs";

const THEME = {
  obsidian: "09090B",
  zinc900: "18181B",
  zinc800: "27272A",
  zinc600: "52525B",
  zinc500: "71717A",
  zinc400: "A1A1AA",
  zinc200: "E4E4E7",
  zinc100: "F4F4F5",
  offWhite: "FAFAFA",
  white: "FFFFFF",
};

// Splits "Key Term: Detailed explanation..." so the lead-in renders in bold
const splitLeadIn = (text) => {
  const match = String(text || "").match(/^([^:]{2,48}:)\s+([\s\S]+)$/);
  if (match) {
    return { lead: match[1], body: match[2] };
  }
  return { lead: "", body: String(text || "") };
};

export const generatePpt = async (data = {}) => {
  const title = String(data?.title || "Generated Presentation").trim();
  const subtitle = String(data?.subtitle || "").trim();
  const slides = Array.isArray(data?.slides) ? data.slides : [];

  const pptx = new PptxGenJS();
  pptx.layout = "LAYOUT_WIDE"; // 13.333 x 7.5 inches
  pptx.author = "NovaAI";
  pptx.company = "NovaAI";
  pptx.title = title;
  pptx.subject = subtitle || title;

  const formattedDate = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });

  // ---------------------------------------------------------
  // 1. COVER SLIDE (Dark Monochrome Obsidian Theme)
  // ---------------------------------------------------------
  const cover = pptx.addSlide();
  cover.background = { color: THEME.obsidian };

  // Top accent bar & brand tag
  cover.addShape(pptx.ShapeType.rect, {
    x: 0.9,
    y: 1.35,
    w: 0.65,
    h: 0.06,
    fill: { color: THEME.white },
  });

  cover.addText(`NOVAAI PRESENTATION  •  ${formattedDate.toUpperCase()}`, {
    x: 0.9,
    y: 1.55,
    w: 11.5,
    h: 0.35,
    fontFace: "Arial",
    fontSize: 10,
    bold: true,
    color: THEME.zinc400,
    charSpacing: 1.5,
  });

  // Main Deck Title
  cover.addText(title, {
    x: 0.9,
    y: 2.15,
    w: 11.4,
    h: 2.1,
    fontFace: "Arial",
    fontSize: 38,
    bold: true,
    color: THEME.white,
    valign: "top",
    lineSpacingMultiple: 1.15,
    fit: "shrink",
  });

  // Subtitle
  if (subtitle) {
    cover.addText(subtitle, {
      x: 0.9,
      y: 4.35,
      w: 10.6,
      h: 1.1,
      fontFace: "Arial",
      fontSize: 17,
      color: THEME.zinc400,
      valign: "top",
      lineSpacingMultiple: 1.25,
      fit: "shrink",
    });
  }

  // Bottom divider & slide count metadata
  cover.addShape(pptx.ShapeType.rect, {
    x: 0.9,
    y: 6.55,
    w: 11.53,
    h: 0.015,
    fill: { color: THEME.zinc800 },
  });

  cover.addText(`${slides.length} Content Slides`, {
    x: 0.9,
    y: 6.72,
    w: 5.0,
    h: 0.3,
    fontFace: "Arial",
    fontSize: 10,
    color: THEME.zinc500,
  });

  cover.addText("Generated by NovaAI", {
    x: 7.43,
    y: 6.72,
    w: 5.0,
    h: 0.3,
    fontFace: "Arial",
    fontSize: 10,
    color: THEME.zinc500,
    align: "right",
  });

  // ---------------------------------------------------------
  // 2. CONTENT SLIDES (Clean Light Executive Layout)
  // ---------------------------------------------------------
  const totalDeckSlides = slides.length + 2; // Cover + Content + Closing

  slides.forEach((slideData, idx) => {
    const slide = pptx.addSlide();
    slide.background = { color: THEME.offWhite };

    const slideTitle = String(
      slideData?.title || `Slide ${idx + 1}`
    ).trim();
    const rawPoints = Array.isArray(slideData?.points) ? slideData.points : [];
    const points = rawPoints
      .map((pt) => String(pt || "").trim())
      .filter(Boolean);

    const slideBadge = String(idx + 1).padStart(2, "0");

    // Top monochrome accent bar
    slide.addShape(pptx.ShapeType.rect, {
      x: 0,
      y: 0,
      w: 13.333,
      h: 0.08,
      fill: { color: THEME.obsidian },
    });

    // Slide number pill badge
    slide.addShape(pptx.ShapeType.roundRect, {
      x: 0.85,
      y: 0.58,
      w: 0.56,
      h: 0.38,
      rectRadius: 0.08,
      fill: { color: THEME.zinc900 },
    });

    slide.addText(slideBadge, {
      x: 0.85,
      y: 0.58,
      w: 0.56,
      h: 0.38,
      fontFace: "Arial",
      fontSize: 11,
      bold: true,
      color: THEME.white,
      align: "center",
      valign: "middle",
    });

    // Slide Heading
    slide.addText(slideTitle, {
      x: 1.56,
      y: 0.5,
      w: 10.9,
      h: 0.65,
      fontFace: "Arial",
      fontSize: 23,
      bold: true,
      color: THEME.obsidian,
      valign: "middle",
      fit: "shrink",
    });

    // Header separator line
    slide.addShape(pptx.ShapeType.rect, {
      x: 0.85,
      y: 1.28,
      w: 11.63,
      h: 0.015,
      fill: { color: THEME.zinc200 },
    });

    // Main content card container so wrapped points stay neatly framed
    slide.addShape(pptx.ShapeType.roundRect, {
      x: 0.85,
      y: 1.52,
      w: 11.63,
      h: 5.1,
      rectRadius: 0.1,
      fill: { color: THEME.white },
      line: { color: THEME.zinc200, width: 1 },
    });

    // Build wrapped bullet text runs with bold lead-ins
    const fontSize = points.length >= 6 ? 14.5 : 16;
    const paraSpaceAfter = points.length >= 6 ? 10 : 14;
    const bulletRuns = [];

    points.forEach((point, pIdx) => {
      const { lead, body } = splitLeadIn(point);
      const isLast = pIdx === points.length - 1;

      if (lead) {
        bulletRuns.push({
          text: `${lead} `,
          options: {
            fontFace: "Arial",
            fontSize,
            bold: true,
            color: THEME.obsidian,
            bullet: { code: "2022", color: THEME.zinc900 },
            paraSpaceAfter,
            lineSpacingMultiple: 1.2,
          },
        });
        bulletRuns.push({
          text: body,
          options: {
            fontFace: "Arial",
            fontSize,
            bold: false,
            color: THEME.zinc600,
            breakLine: !isLast,
            paraSpaceAfter,
            lineSpacingMultiple: 1.2,
          },
        });
      } else {
        bulletRuns.push({
          text: body,
          options: {
            fontFace: "Arial",
            fontSize,
            bold: false,
            color: THEME.zinc600,
            bullet: { code: "2022", color: THEME.zinc900 },
            breakLine: !isLast,
            paraSpaceAfter,
            lineSpacingMultiple: 1.2,
          },
        });
      }
    });

    if (bulletRuns.length > 0) {
      slide.addText(bulletRuns, {
        x: 1.2,
        y: 1.78,
        w: 10.95,
        h: 4.58,
        valign: "top",
        wrap: true,
        fit: "shrink",
      });
    }

    // Footer bar
    slide.addText(title, {
      x: 0.85,
      y: 6.88,
      w: 8.5,
      h: 0.3,
      fontFace: "Arial",
      fontSize: 9.5,
      color: THEME.zinc400,
    });

    slide.addText(`Slide ${idx + 2} of ${totalDeckSlides}`, {
      x: 9.5,
      y: 6.88,
      w: 2.98,
      h: 0.3,
      fontFace: "Arial",
      fontSize: 9.5,
      color: THEME.zinc500,
      align: "right",
    });
  });

  // ---------------------------------------------------------
  // 3. CLOSING SLIDE
  // ---------------------------------------------------------
  const closing = pptx.addSlide();
  closing.background = { color: THEME.obsidian };

  closing.addShape(pptx.ShapeType.rect, {
    x: 6.16,
    y: 2.55,
    w: 1.0,
    h: 0.05,
    fill: { color: THEME.white },
  });

  closing.addText("Thank You", {
    x: 1.0,
    y: 2.85,
    w: 11.33,
    h: 0.9,
    fontFace: "Arial",
    fontSize: 36,
    bold: true,
    color: THEME.white,
    align: "center",
  });

  closing.addText(title, {
    x: 1.5,
    y: 3.8,
    w: 10.33,
    h: 0.6,
    fontFace: "Arial",
    fontSize: 15,
    color: THEME.zinc400,
    align: "center",
    fit: "shrink",
  });

  closing.addText(`Generated by NovaAI  •  ${formattedDate}`, {
    x: 1.5,
    y: 6.65,
    w: 10.33,
    h: 0.35,
    fontFace: "Arial",
    fontSize: 10,
    color: THEME.zinc500,
    align: "center",
  });

  return await pptx.write({ outputType: "nodebuffer" });
};